"""Integration test against a deployed environment (CI: staging, after `bundle deploy -t staging`).

No LocalStack or mock API needed: the test writes deterministic fixture pulls (generated by the
same generator + parser the poller uses) straight into the environment's landing volume, runs
the PH pipeline, and asserts the medallion invariants.

    uv run pytest -m integration tests/integration --env staging
"""

import subprocess
import uuid
from datetime import UTC, datetime, timedelta

import pytest
from databricks.sdk import WorkspaceClient

from ingestion.config import Settings
from ingestion.legacy_parser import to_parquet_bytes, to_table
from ingestion.models import PullTask, iso
from ingestion.sinks import VolumeSink
from mock_pos_api.generator import window_lines
from scripts.dbsql import run, warehouse_id

pytestmark = pytest.mark.integration


@pytest.fixture(scope="module")
def ctx(request):
    env = request.config.getoption("--env")
    w = WorkspaceClient()
    return {"env": env, "w": w, "wh": warehouse_id(w)}


def q(ctx, sql):
    return run(ctx["w"], ctx["wh"], sql, show=False)


def test_pipeline_dedupes_quarantines_and_aggregates(ctx):
    env, w = ctx["env"], ctx["w"]
    # A fixed historical window (void states final), unique per test run so reruns are independent.
    run_id = uuid.uuid4().hex[:6]
    ws = datetime(2026, 10, 20, 4, 0, tzinfo=UTC) + timedelta(minutes=int(run_id, 16) % 5000)
    ws = ws.replace(second=0)
    we = ws + timedelta(minutes=5)
    lines = window_lines("PH", ws, we, ws + timedelta(hours=2), 50000)
    t1 = PullTask("PH", iso(ws), iso(we), "live", iso(we + timedelta(minutes=1)), iso(we))
    t2 = PullTask("PH", iso(ws), iso(we), "repull", iso(we + timedelta(minutes=22)), iso(we))  # same window again
    sink = VolumeSink(w, Settings(env=env).volume_root)
    for t in (t1, t2):
        sink.put("PH", t.object_key(), to_parquet_bytes(to_table(lines, t)))

    subprocess.run(["databricks", "bundle", "run", "pos_ph", "-t", env], check=True, capture_output=True)

    pred = f"_window_start = '{iso(ws)}'"
    bronze = int(q(ctx, f"SELECT count(*) FROM pos_ph.{env}_bronze.pos_lines_raw WHERE {pred}")[0][0])
    silver, keys = map(int, q(ctx, f"""SELECT count(*), count(DISTINCT store_id, register_id, txn_id, line_no)
                                       FROM pos_ph.{env}_silver.pos_lines WHERE {pred}""")[0])
    q_rows, q_distinct = map(int, q(ctx, f"""SELECT count(*), count(DISTINCT _raw_line)
                                              FROM pos_ph.{env}_silver.pos_lines_quarantine WHERE {pred}""")[0])
    unique_lines = len(set(lines))

    assert bronze == 2 * unique_lines, "bronze keeps every pulled version"
    assert silver == keys, "silver has exactly one row per business key"
    assert 0 < q_distinct < unique_lines * 0.02, "malformed rows go to quarantine, not silver"
    assert q_rows == 2 * q_distinct, "quarantine is append-only: one row per bad line per pull"
    assert silver + q_distinct == unique_lines, "every distinct line is either in silver or quarantined"
    gold = int(q(ctx, f"SELECT count(*) FROM pos_ph.{env}_gold.sales_by_store_hour WHERE txn_hour_utc = '{iso(ws.replace(minute=0))}'")[0][0])
    assert gold > 0


def test_security_functions_and_masks_exist(ctx):
    env = ctx["env"]
    fns = {r[0] for r in q(ctx, "SELECT routine_name FROM pos_ph.information_schema.routines WHERE routine_schema = 'security'")}
    assert {"rf_country", "mask_pii", "mask_email"} <= fns
    desc = " ".join(str(r) for r in q(ctx, f"DESCRIBE TABLE EXTENDED pos_ph.{env}_gold.sales_by_store_hour"))
    assert "rf_country" in desc, "row filter attached to gold"
